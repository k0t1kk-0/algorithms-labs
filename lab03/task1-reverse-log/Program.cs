// Лабораторна 3, задача 1. Журнал у зворотному порядку.
// Рядки додаються лише в КІНЕЦЬ списку (Add), без вставки на початок.
// Порядок змінюється один раз, після того як усе зібрано (Reverse — один прохід, O(n)).

Console.OutputEncoding = System.Text.Encoding.UTF8;

string[] input =
[
    "08:00 Сервер запущено",
    "08:05 Користувач увійшов",
    "08:12 Створено замовлення №101",
    "08:20 Оплату підтверджено",
    "08:31 Користувач вийшов"
];

var log = new List<string>();
foreach (var line in input)
    log.Add(line);              // додавання в кінець — без зсуву елементів

log.Reverse();                  // розворот один раз після збору

Console.WriteLine("Журнал у зворотному порядку:");
foreach (var line in log)
    Console.WriteLine(line);
