// Лабораторна 3, задача 3. Останні N подій (кільцевий буфер).
// Масив на N позицій і номер комірки для наступного запису. Коли доходимо до кінця — починаємо з нуля.
// Найстаріша подія не видаляється з початку (без зсуву): її просто перезаписує нова.

Console.OutputEncoding = System.Text.Encoding.UTF8;

const int N = 5;
var buffer = new string[N];
int next = 0;     // куди писати наступну подію
int count = 0;    // скільки подій зараз збережено (не більше N)

string[] stream =
[
    "Подія 1", "Подія 2", "Подія 3", "Подія 4", "Подія 5",
    "Подія 6", "Подія 7", "Подія 8"
];

foreach (var ev in stream)
{
    buffer[next] = ev;              // перезапис найстарішої, якщо буфер повний
    next = (next + 1) % N;          // перехід по колу
    if (count < N) count++;
}

// Найстаріша подія: якщо буфер заповнений — у комірці next, інакше — у комірці 0.
int start = count < N ? 0 : next;

Console.WriteLine($"Останні {count} подій (від найстарішої до найновішої):");
for (int k = 0; k < count; k++)
    Console.WriteLine(buffer[(start + k) % N]);
